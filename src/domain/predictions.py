"""Predictions, outcome classes, and probability vector domain models.

Enforces Section 3.8 & 3.9:
- 3 outcome classes: UP, FLAT, DOWN
- Sum to 1.0 within strict numerical tolerance (1e-5)
- Pillar-level predictions and late-fusion calibrated ensemble outputs
"""

import math
from dataclasses import dataclass
from enum import StrEnum

from src.domain.errors import InvariantViolationError
from src.domain.features import PillarType


class OutcomeClass(StrEnum):
    """The 3 mutually exclusive target outcome classes."""

    UP = "UP"
    FLAT = "FLAT"
    DOWN = "DOWN"


@dataclass(frozen=True, slots=True)
class ProbabilityVector:
    """Calibrated probability vector over {UP, FLAT, DOWN} summing to 1.0."""

    p_up: float
    p_flat: float
    p_down: float

    def __post_init__(self) -> None:
        for name, val in [("p_up", self.p_up), ("p_flat", self.p_flat), ("p_down", self.p_down)]:
            if math.isnan(val) or math.isinf(val):
                raise InvariantViolationError(f"{name} cannot be NaN or Inf")
            if val < 0.0 or val > 1.0:
                raise InvariantViolationError(
                    f"{name} ({val}) must be in range [0.0, 1.0]",
                    details={"class": name, "value": val},
                )

        prob_sum = self.p_up + self.p_flat + self.p_down
        if abs(prob_sum - 1.0) > 1e-5:
            raise InvariantViolationError(
                f"Probabilities must sum to 1.0 (+/- 1e-5), got {prob_sum:.6f}",
                details={
                    "sum": prob_sum,
                    "p_up": self.p_up,
                    "p_flat": self.p_flat,
                    "p_down": self.p_down,
                },
            )

    @property
    def largest_class(self) -> OutcomeClass:
        """Return the class with the maximum probability."""
        if self.p_up > self.p_flat and self.p_up > self.p_down:
            return OutcomeClass.UP
        if self.p_down > self.p_flat and self.p_down > self.p_up:
            return OutcomeClass.DOWN
        return OutcomeClass.FLAT

    @property
    def margin_up_down(self) -> float:
        """Margin between p_up and p_down."""
        return self.p_up - self.p_down

    @property
    def margin_down_up(self) -> float:
        """Margin between p_down and p_up."""
        return self.p_down - self.p_up


@dataclass(frozen=True, slots=True)
class PillarPrediction:
    """Prediction generated by an individual pillar expert model."""

    pillar: PillarType
    probabilities: ProbabilityVector
    quality_factor: float  # q_m in [0.0, 1.0]

    def __post_init__(self) -> None:
        if self.quality_factor < 0.0 or self.quality_factor > 1.0:
            raise InvariantViolationError("quality_factor must be in [0.0, 1.0]")

    def agrees_with_direction(self, outcome: OutcomeClass) -> bool:
        """Check if standalone directional probability exceeds FLAT and opposite direction."""
        if outcome == OutcomeClass.UP:
            return (
                self.probabilities.p_up > self.probabilities.p_flat
                and self.probabilities.p_up > self.probabilities.p_down
            )
        if outcome == OutcomeClass.DOWN:
            return (
                self.probabilities.p_down > self.probabilities.p_flat
                and self.probabilities.p_down > self.probabilities.p_up
            )
        return False
